"""Where uploaded file bytes live.

The app talks to FileStorage only, so the local-disk implementation used in development can
be swapped for Cloudflare R2 (or any S3-compatible store) without touching the routes.
"""

from collections.abc import AsyncIterable, AsyncIterator
from pathlib import Path
from typing import Protocol

import anyio

_CHUNK_SIZE = 64 * 1024


class FileStorage(Protocol):
    async def save(self, key: str, chunks: AsyncIterable[bytes]) -> None:
        """Store a stream under key. Nothing is left behind if the stream raises."""

    async def open(self, key: str) -> AsyncIterator[bytes]:
        """Open key for reading, raising FileNotFoundError at once if it doesn't exist."""

    async def delete(self, key: str) -> None:
        """Delete key. Deleting a missing key is not an error, so retries are safe."""


class LocalFileStorage:
    def __init__(self, root: str | Path) -> None:
        self.root = Path(root).resolve()

    def _path(self, key: str) -> Path:
        path = (self.root / key).resolve()
        # Keys are generated by the server, but never let one escape the storage root.
        if not path.is_relative_to(self.root) or path == self.root:
            raise ValueError("Invalid storage key")
        return path

    async def save(self, key: str, chunks: AsyncIterable[bytes]) -> None:
        path = self._path(key)
        await anyio.Path(path.parent).mkdir(parents=True, exist_ok=True)
        # Write to a temporary name and rename at the end, so a half-written file never
        # appears under its real key.
        partial = path.with_name(path.name + ".part")
        try:
            async with await anyio.open_file(partial, "wb") as file:
                async for chunk in chunks:
                    await file.write(chunk)
            await anyio.Path(partial).replace(path)
        except BaseException:
            # Synchronous on purpose: this also runs on cancellation, where awaiting may not.
            partial.unlink(missing_ok=True)
            raise

    async def open(self, key: str) -> AsyncIterator[bytes]:
        file = await anyio.open_file(self._path(key), "rb")

        async def chunks() -> AsyncIterator[bytes]:
            async with file:
                while chunk := await file.read(_CHUNK_SIZE):
                    yield chunk

        return chunks()

    async def delete(self, key: str) -> None:
        await anyio.Path(self._path(key)).unlink(missing_ok=True)
